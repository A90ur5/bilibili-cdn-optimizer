// Builds bilibili-cdn-tw/chrome-extension-tw/ and bilibili-cdn-tw/chrome-extension-tw.zip from
// bilibili-cdn-tw/bilibili-cdn-tw.user.js (the Greasy Fork "Bilibili CDN 台灣優化" script).
//
//   node tools/build-extension-tw.js           regenerate manifest.json, bilibili-cdn-tw.js and the zip
//   node tools/build-extension-tw.js --check   fail if any of them on disk differs from a fresh build
//
// The zip is committed so it can be downloaded straight from GitHub. It is written uncompressed with
// fixed timestamps, so the same inputs always give the same bytes and --check can compare it.
//
// Unlike chrome-extension/, the output cannot be a plain copy. Tampermonkey does two things for this
// script that a Chrome content script does not, and both have to be reproduced here:
//   1. It wraps the script in a function. This script declares ~270 top-level const/let/function names;
//      run bare in the MAIN world they would land in the page's global scope, and a B站 script that
//      declares the same name at top level would then throw on load.
//   2. It provides the GM_* APIs the header @grants. The shim below covers exactly those grants, and the
//      build refuses a header that asks for anything else, so a future upstream update that adds e.g.
//      GM_xmlhttpRequest fails here instead of producing an extension that breaks at runtime.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const DIR = path.join(__dirname, '..', 'bilibili-cdn-tw');
const SRC = path.join(DIR, 'bilibili-cdn-tw.user.js');
const EXT = 'chrome-extension-tw';
const OUT_JS = 'bilibili-cdn-tw.js';
const ZIP = EXT + '.zip';
const README = 'README.md';
const SHIMMED = ['GM_getValue', 'GM_setValue', 'GM_deleteValue', 'GM_registerMenuCommand', 'GM_info', 'unsafeWindow'];

function fail(msg) { console.error('build-extension-tw: ' + msg); process.exit(1); }

function parseHeader(src) {
  const m = src.match(/\/\/ ==UserScript==\n([\s\S]*?)\n\/\/ ==\/UserScript==/);
  if (!m) fail('no ==UserScript== header in ' + SRC);
  const h = {};
  for (const line of m[1].split('\n')) {
    // the value is optional: a bare `// @noframes` line still has to register
    const kv = line.match(/^\/\/ @(\S+)(?:\s+(.*?))?\s*$/);
    if (kv) (h[kv[1]] = h[kv[1]] || []).push(kv[2] || '');
  }
  return h;
}

function build(src) {
  const h = parseHeader(src);
  const one = (k) => (h[k] || [])[0];
  const name = one('name'), version = one('version'), description = one('description') || '';
  const matches = h.match || [];

  if (!name) fail('@name is missing');
  if (!/^\d+(\.\d+){0,3}$/.test(version || '')) fail('@version "' + version + '" is not a valid Chrome extension version');
  if (one('run-at') !== 'document-start') fail('@run-at must be document-start, got ' + one('run-at'));
  if (!matches.length) fail('no @match lines');
  for (const k of ['include', 'exclude', 'exclude-match', 'require', 'resource', 'connect']) {
    if (h[k]) fail('@' + k + ' is not supported by this build; extend it before shipping');
  }
  const unshimmed = (h.grant || []).filter(g => !SHIMMED.includes(g));
  if (unshimmed.length) fail('no shim for @grant ' + unshimmed.join(', ') + '; extend the shim before shipping');
  if (description.length > 132) fail('@description is longer than Chrome allows (132)');

  const manifest = {
    manifest_version: 3,
    name,
    version,
    description,
    minimum_chrome_version: '111',
    content_scripts: [{
      matches,
      js: [OUT_JS],
      run_at: 'document_start',
      // Tampermonkey runs a script in frames too unless it says @noframes
      all_frames: !h.noframes,
      // ISOLATED (the default) has its own window: patching fetch/XHR/Worker there changes nothing the page sees
      world: 'MAIN',
    }],
  };

  const js = `// Generated by tools/build-extension-tw.js from bilibili-cdn-tw.user.js. Do not edit by hand:
// edit the userscript, then run \`node tools/build-extension-tw.js\`.
//
// What Tampermonkey would otherwise provide:
//   GM_getValue / GM_setValue / GM_deleteValue  the page's localStorage under the "BiliCDN_TW:" prefix.
//                                               Both are synchronous, so the script sees the same semantics.
//   GM_info                                     { script: { name, version } } from the header.
//   unsafeWindow                                the page window itself (this runs in the MAIN world).
//   GM_registerMenuCommand                      left undefined. The script checks for it and skips the
//                                               menu; every item is also on its in-player settings panel
//                                               or the BiliCDN console API.
;(function () {
  let store = null
  try { store = window.localStorage } catch (e) { /* sandboxed frame: settings just do not persist */ }
  const PREFIX = 'BiliCDN_TW:'
  const GM_getValue = (key, def) => {
    try {
      const raw = store && store.getItem(PREFIX + key)
      return raw == null ? def : JSON.parse(raw)
    } catch (e) { return def }
  }
  const GM_setValue = (key, value) => {
    try {
      if (value === undefined) store && store.removeItem(PREFIX + key)
      else store && store.setItem(PREFIX + key, JSON.stringify(value))
    } catch (e) { /* quota or privacy mode: the script keeps working, it just forgets */ }
  }
  const GM_deleteValue = (key) => {
    try { store && store.removeItem(PREFIX + key) } catch (e) {}
  }
  const GM_info = Object.freeze({ script: Object.freeze({ name: ${JSON.stringify(name)}, version: ${JSON.stringify(version)} }) })

  ;(function (GM_getValue, GM_setValue, GM_deleteValue, GM_registerMenuCommand, GM_info, unsafeWindow) {
// ======== bilibili-cdn-tw.user.js, verbatim ========
${src}// ======== end of bilibili-cdn-tw.user.js ========
  }).call(window, GM_getValue, GM_setValue, GM_deleteValue, undefined, GM_info, window)
})()
`;
  return { manifest: JSON.stringify(manifest, null, 2) + '\n', js };
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

// Minimal zip: stored (no compression), DOS date fixed at 1980-01-01, entries in the given order.
function zip(entries) {
  const locals = [], centrals = [];
  let offset = 0;
  for (const [name, text] of entries) {
    const data = Buffer.from(text, 'utf8'), fname = Buffer.from(name, 'utf8'), crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(10, 4); local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(0, 8); local.writeUInt16LE(0, 10); local.writeUInt16LE(0x21, 12);
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(data.length, 18); local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(fname.length, 26); local.writeUInt16LE(0, 28);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(10, 6);
    central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(0, 10); central.writeUInt16LE(0, 12);
    central.writeUInt16LE(0x21, 14); central.writeUInt32LE(crc, 16); central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24); central.writeUInt16LE(fname.length, 28); central.writeUInt32LE(offset, 42);
    locals.push(local, fname, data);
    centrals.push(central, fname);
    offset += local.length + fname.length + data.length;
  }
  const cd = Buffer.concat(centrals), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}

const src = fs.readFileSync(SRC, 'utf8');
if (!src.endsWith('\n')) fail(SRC + ' must end with a newline');
const out = build(src);
// compiles only, never runs: catches a wrapper that no longer parses around a new upstream version
try { new vm.Script(out.js, { filename: OUT_JS }); } catch (e) { fail('generated script does not parse: ' + e.message); }

const readme = fs.readFileSync(path.join(DIR, README), 'utf8');
const files = {
  [EXT + '/manifest.json']: Buffer.from(out.manifest, 'utf8'),
  [EXT + '/' + OUT_JS]: Buffer.from(out.js, 'utf8'),
  // the zip carries the README too, for anyone who downloads only the zip
  [ZIP]: zip([[EXT + '/manifest.json', out.manifest], [EXT + '/' + OUT_JS, out.js], [README, readme]]),
};
if (process.argv.includes('--check')) {
  let bad = 0;
  for (const [f, want] of Object.entries(files)) {
    const p = path.join(DIR, f);
    const have = fs.existsSync(p) ? fs.readFileSync(p) : null;
    if (have && have.equals(want)) console.log('  PASS  bilibili-cdn-tw/' + f + ' is up to date');
    else { bad++; console.log('  FAIL  bilibili-cdn-tw/' + f + (have === null ? ' is missing' : ' is stale') + '  <- run: node tools/build-extension-tw.js'); }
  }
  process.exit(bad ? 1 : 0);
}
fs.mkdirSync(path.join(DIR, EXT), { recursive: true });
for (const [f, data] of Object.entries(files)) fs.writeFileSync(path.join(DIR, f), data);
console.log('wrote ' + Object.keys(files).map(f => 'bilibili-cdn-tw/' + f).join(', '));
